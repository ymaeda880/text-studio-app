# ============================================================
OPTIONS_TEXT = """
<div style="line-height:1.7">

## 出力スタイル

出力スタイルは，中間テキストをどの程度構造化して出すかを決める設定です．

---

## 簡素

できるだけプレーンなテキストに近い形で出力します．

向いている用途：

- 人が目視で確認したい
- マーカーが多いと読みにくい
- 軽い前処理だけでよい

特徴：

- 見出し，表，図は最小限の区切りで出力します．
- 表はJSON化せず，読みやすいテキストとして出します．
- 図はキャプション中心に扱います．

---

## 標準

実運用で最も使いやすい推奨モードです．

向いている用途：

- 文章校正に進む
- Inbox に保存して再利用する
- 見出しや表の構造をある程度保ちたい

特徴：

- 見出し候補を `<ここから見出し>` で括ります．
- 表を `<ここから表>` で括ります．
- 図を `<ここから図>` で括ります．
- Inbox保存時の分割とも相性がよいです．

---

## 詳細

後段で機械処理しやすいように，より明示的なマーカーを付けます．

向いている用途：

- 構造情報をできるだけ残したい
- 表をJSONとして扱いたい
- 後でプログラム処理したい

特徴：

- 見出しに `HEADING[...]` 形式のIDを付けます．
- 図に `FIGURE[...]` 形式のマーカーを付けます．
- 表はJSON形式を含めて出力します．

</div>
"""


