TEXT_STYLE_TEXT = r"""

##### 1. 文字書式

wordTexでは，通常段落の中で，文字の大きさ，色，太字，斜体，下線を指定できます．

本文中に次の形で書きます．

    {\装飾コマンド 本文}

例

    これは{\bold 重要な文字}です。

---

##### 2. 文字の大きさ

文字サイズは次の3種類を指定できます．

    {\small 小さい文字}

    {\large 大きい文字}

    {\Large さらに大きい文字}

現在のサイズは次のとおりです．

- small：9pt
- large：14pt
- Large：18pt

---

##### 3. 文字色

色名を使って文字色を指定できます．

    {\red 赤い文字}

    {\blue 青い文字}

    {\green 緑の文字}

    {\gray 灰色の文字}

また，16進数カラーも指定できます．

    {\color=#FF0000 赤い文字}

    {\color=#0000FF 青い文字}

---

##### 4. 太字

太字にする場合は，bold を使います．

    {\bold 太字の文字}

---

##### 5. 斜体

斜体にする場合は，italic を使います．

    {\italic 斜体の文字}

---

##### 6. 下線

下線を付ける場合は，underline を使います．

    {\underline 下線付きの文字}

---

##### 7. 複数指定

複数の装飾を同時に指定できます．

    {\large\bold\red 大きい赤太字}

    {\Large\underline\blue 大きい青下線}

---

##### 8. 使用できる色名

文字色には，共通色として定義されている色名を使えます．

- black
- gray / grey
- red
- green
- blue
- cyan
- magenta
- yellow
- orange
- purple
- brown

---

##### 9. 注意

現在のインライン装飾は，通常段落内の簡易装飾です．

入れ子の装飾には対応していません．

例

    {\bold 太字の中に{\red 赤文字}}

のような入れ子は，現在の対象外です．

"""