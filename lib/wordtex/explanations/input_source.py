INPUT_LOGIC_TEXT = r"""

##### 1. wordTexソースの入力方法

wordTexでは，ソーステキスト（`.wtex`）を入力として使用します．

入力方法は次の3種類です．

- テキスト貼り付け
- `.wtex` ファイルのアップロード
- InBoxから `.wtex` ファイルを選択

どの方法で入力しても，最終的には同じソーステキストとして扱われます．

---

##### 2. テキスト貼り付け

画面へ直接ソーステキストを貼り付けます．

試験的な文章や小規模な文書を作成する場合に便利です．

貼り付け後，「wordTexを解析」を押すことで解析を開始します．

---

##### 3. ファイルアップロード

既に保存してある `.wtex` ファイルをアップロードできます．

アップロードされたファイルは UTF-8 として読み込みます．

UTF-8以外の場合は，文字化けを避けるため置換モードで読み込みます．

---

##### 4. InBoxから選択

InBox内の `.wtex` ファイルだけを一覧表示します．

目的のファイルを選択すると，
その内容を読み込んで解析対象にします．

Word文書やPDFなどは表示対象になりません．

---

##### 5. 入力後の処理

入力が確定すると，

- ソーステキスト
- ファイル名
- 入力シグネチャ

を session_state に保存します．

その後，

- 前回解析結果
- 前回生成したWord
- 前回プレビュー

を破棄します．

入力内容が変わった場合は，
必ず新しい解析結果を使用します．

---

##### 6. 入力シグネチャ

入力内容が変更されたかどうかは，

- 入力方法
- ファイル名
- バイト数
- 文字数

から入力シグネチャを作成し，
前回と比較して判定します．

変更があった場合のみ，
解析結果をリセットします．

"""