# ============================================================
# ページ上部説明UI
# ============================================================
def render_toc_page_intro() -> None:

    # ------------------------------------------------------------
    # ページ概要
    # ------------------------------------------------------------

    render_info_card_compact(
body_html="""
🟢 このページでは，<b>AIを使用</b>しません．</b>．
""",
)

    render_info_card_compact(
        body_html="""
このページでは，PDFの目次を本文テキストの実際のページ番号と照合します．
""",
    )

    # ------------------------------------------------------------
    # 使い方
    # ------------------------------------------------------------
    render_info_card_bullets_compact_custom(
        title="使い方",
        items=[
            ("①", "チェックを行いたい<b>PDFファイルをアップロードします．</b>"),
            ("", "⚠️ このページはPDF専用です．Wordファイルは対象外です．"),
            ("②", "<b>「チェックを実行」を押します．</b>"),
            ("③", "<b>「結果をExcelで保存」を押して結果をダウンロードします．</b>"),
        ],
    )

    st.markdown(
        "<div style='height:16px'></div>",
        unsafe_allow_html=True,
    )

    # ------------------------------------------------------------
    # 注意事項
    # ------------------------------------------------------------
    render_info_card_compact(
        title="お願い",
        body_html="""
　このツールは，ルールベースのパターン照合によって目次と本文を確認しています．
PDFのレイアウトや文字化け，特殊な表記方法によっては，正しく判定できない場合があります．結果は必ず利用者自身で確認してください．<br>
　正しく判定されなかった時は，管理者に報告してください．プログラムを変更して対応します．
""",
    )

    st.markdown(
        "<div style='height:16px'></div>",
        unsafe_allow_html=True,
    )


# ============================================================
# public API：詳細説明 expander
# ============================================================
def render_toc_logic_expander(
    *,
    theme: dict[str, Any] | None = None,
    banner_key: str = "purple_light",
) -> None:
    render_themed_help_expander(
        expander_key=HELP_EXPANDER_KEY,
        expander_title=HELP_EXPANDER_TITLE,
        tabs=HELP_TABS,
        theme=theme,
        banner_key=banner_key,
        expanded=False,
    )


# ============================================================
