HELP_EXPANDER_TITLE = "📌 詳細説明（クリックで展開）"


# ============================================================
# 詳細説明：概要
# ============================================================
OVERVIEW_TEXT = """

##### 一括Word校正ページの概要

このページでは，

- Word解析
- 中間テキスト生成
- AI文章校正
- 校正レポート出力

を一括して行います．

---

##### 処理の流れ

###### 1. Word解析

まず，Word(.docx) ファイルを解析します．<br>
Word解析では，

- 見出し
- 本文
- 箇条書き
- 表
- 改行構造

などを解析し，中間テキストを生成します．<br>
Word解析の詳細は，<b>「Word解析」ページの説明</b>を参照してください．

---

###### 2. 中間テキスト保存

生成された中間テキストは，サーバー内部（Storages/&lt;sub&gt;/word_edit_app/）に保存されます．<br>
長い文書は，30,000文字以下程度になるように自動分割されます．

---

###### 3. AI文章校正

保存済み中間テキストを選択し，
AIによる文章校正を行います．<br>
文章校正では，

- 誤字脱字
- 表現ゆれ
- 用語統一
- 不自然な文章
- 読みにくい箇所

などを解析します．<br>
文章校正ロジックの詳細は，<b>「文章校正」ページの説明</b>を参照してください．

---

###### 4. レポート出力

解析結果は：

- PDF
- Word

形式でダウンロードできます．

</div>
"""


