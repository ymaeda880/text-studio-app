WORD_ANALYSIS_TEXT = """

##### Word解析とは

Word文書には本文だけでなく，

- 見出し
- 箇条書き
- 表
- セル
- 結合セル
- 改行

などの文書構造があります．

このページでは，
Word文書をそのままプレーンテキストへ変換するのではなく，
これらの構造を可能な範囲で保持した
<b>中間テキスト</b>を作成します．

---

##### 表

Wordの表は，
AIが表として認識できる形式へ変換します．

表の各行やセルの関係を保持し，
横方向に結合されたセルについては，
設定により<b>&lt;同左&gt;</b>を使用します．

これによりAIは，
単なる文章の並びではなく，
表として内容を判断できます．

---

##### 見出し

Wordの見出しについても，
本文とは区別できるように中間テキストへ変換します．

これによりAIは，
文書の章・節などの構造を考慮して校正できます．

---

##### Word変換に伴う表示

Wordから中間テキストへ変換する過程では，

- 空白
- 改行
- 数式
- 上付き文字
- 表のセル配置

などが元のWord表示と完全には一致しない場合があります．

AIには，このような変換上の差異を
不用意に校正対象としないよう指示しています．

"""

# ============================================================
# 詳細説明：重要度
# ============================================================
IMPORTANCE_TEXT = """

##### 重要度とは

AIは，校正が必要と判断した箇所について，
<b>「校正の必要性」</b>を0～10の重要度で評価します．

数字が大きいほど，
修正する必要性が高いことを表します．

---

##### 重要度の考え方

重要度は，おおむね次のように解釈してください．

- <b>10</b>：誤字・脱字など，明らかに修正が必要なもの
- <b>7～9</b>：誤りの可能性が高く，修正する必要性が高いもの
- <b>4～6</b>：文章として確認・修正を検討した方がよいもの
- <b>1～3</b>：軽微な問題や，修正するかどうか判断の余地が大きいもの
- <b>0</b>：校正する必要がないもの

重要度はAIによる判断です．
最終的に修正するかどうかは，
原文と修正理由を確認して判断してください．

---

##### 解析モードと重要度

解析モードによって，
校正結果として出力する重要度の範囲が異なります．

###### 通常校正

<b>重要度4以上</b>を校正結果として出力します．

軽微な表現上の問題を過度に指摘せず，
修正を検討した方がよい箇所を中心に抽出します．

---

###### 簡易校正

<b>重要度5以上</b>を校正結果として出力します．

明白な誤りを中心として，
修正の必要性が比較的高い箇所だけを抽出します．

---

###### 厳格校正

厳格校正では，
通常校正より広い範囲を確認します．

現時点では，
<b>重要度による出力下限は設定していません．</b>

そのため，通常校正では出力されない
軽微な指摘が含まれる場合があります．

---

##### 重要度と解析モードの違い

「解析モード」と「重要度」は別のものです．

<b>解析モード</b>は，
AIがどの程度の範囲まで文章を確認するかを指定します．

<b>重要度</b>は，
AIが見つけた個々の校正候補について，
どの程度修正が必要かを0～10で評価した値です．

例えば通常校正では，
文章全体を通常校正の基準で確認した上で，
重要度4以上と判断した項目を校正結果として出力します．

"""

