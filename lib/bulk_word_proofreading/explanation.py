PROOFREADING_MODE_TEXT = """

##### 解析モードとは

このページは<b>Word文書専用</b>です．

そのため，どの解析モードを選択した場合でも，
AIはWord解析によって得られた文書構造を考慮して校正します．

解析モードは，

<b>「Word文書として解析するかどうか」ではなく，
「どの程度の強さで校正するか」</b>

を指定する設定です．

通常は<b>「通常校正」</b>を使用してください．

---

##### 厳格校正

通常校正より広い範囲を確認します．

主に，

- 助詞（てにおは）
- 主語と述語の対応
- 冗長な表現
- 重複表現
- 語順
- 誤字脱字
- 用語の誤用
- 文体の不統一

などを確認します．

文章を詳細に確認したい場合に使用します．

---

##### 通常校正

<b>標準の校正モードです．原則としてこのモードを使用してください．</b>

主に，

- 助詞（てにおは）
- 主語と述語の対応
- 語順
- 誤字脱字
- 用語の誤用
- 文体の不統一
- 不自然な表現

などを確認します．

意味を変更するような過度な書き換えは行わず，
修正が必要な箇所を抽出します．

---

##### 簡易校正

明白な誤りを中心に確認します．

主に，

- 明白な助詞の誤り
- 誤字
- 脱字
- 明確な変換ミス

などを対象とします．

語順変更や表現統一など，
判断の余地が大きい修正は原則として提案しません．

---

##### 3つのモードに共通するWord文書構造の理解

厳格校正・通常校正・簡易校正の
<b>すべてのモードでWord文書構造を考慮します．</b>

例えば，中間テキストに含まれる，

- &lt;ここから表&gt;
- &lt;ここまで表&gt;
- &lt;ここから見出し&gt;
- &lt;ここまで見出し&gt;
- &lt;同左&gt;

などは，Word文書の構造をAIへ伝えるための情報です．

これらの内部マーカーそのものは，
誤字や不要な文字として校正対象にはしません．

また，表については，
表のタイトル・内容と本文中の説明に矛盾がないかも確認します．

"""


