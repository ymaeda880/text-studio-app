# ============================================================
WORD_STRUCTURE_TEXT = """

##### Word文書構造の理解

Word解析によって作成された中間テキストには，
AIが元のWord文書の構造を理解するための情報が含まれています．

例えば，

- &lt;ここから表&gt;
- &lt;ここまで表&gt;
- &lt;ここから見出し&gt;
- &lt;ここまで見出し&gt;
- &lt;同左&gt;

などです．

これらは，
Word文書の構造をAIへ伝えるために
プログラム内部で追加された情報です．

内部マーカーそのものは，
誤字や不要な文字として校正対象にはしません．

---

##### 表

&lt;ここから表&gt;から&lt;ここまで表&gt;までを，
Wordの表として扱います．

表の各行・セルや結合セルの関係を考慮して内容を確認します．

表のタイトルや内容と，
本文中でその表について説明している内容に
矛盾がないかについても確認します．

表のセル内に生じた，

- 改行
- 余分な空白
- 括弧の半角・全角の違い
- 句読点やカンマの違い
- 表変換に伴う表示上の差異

などは，不用意に校正対象としないよう指示しています．

---

##### 見出し

&lt;ここから見出し&gt;と&lt;ここまで見出し&gt;は，
Wordの見出しを表します．

これらの内部マーカー自体は校正対象ではありません．

AIは見出しと本文の違いを考慮して，
文章を確認します．

---

##### Word変換に伴う差異

Word文書から中間テキストへ変換する過程で，

- 空白
- 改行
- 数式
- 上付き文字
- 表のセル配置

などが元のWord表示と完全には一致しない場合があります．

AIには，
このようなWord変換に伴う差異を
不用意に誤りとして指摘しないよう指示しています．

"""


# ============================================================
# 詳細説明：重要度
# ============================================================
IMPORTANCE_TEXT = """

##### 重要度とは

AIは校正候補について，
<b>「校正の必要性」</b>を0～10で評価します．

数字が大きいほど，
修正する必要性が高いことを表します．

プロンプトでは，

- <b>10</b>：明らかな誤字など，確実に修正が必要なもの
- <b>0</b>：校正する必要がないもの

としています．

1～9について固定した区分は設けていません．
AIが個々の校正候補について重要度を判断します．

---

##### 通常校正

通常校正では，
<b>重要度4以上</b>を校正結果として出力します．

---

##### 簡易校正

簡易校正では，
<b>重要度5以上</b>を校正結果として出力します．

---

##### 厳格校正

厳格校正では，
<b>重要度による出力下限を設定していません．</b>

そのため，
通常校正では出力されない軽微な指摘が
含まれる場合があります．

---

##### 校正レベルと重要度の違い

<b>校正レベル</b>は，
AIがどの程度の範囲まで文章を確認するかを指定します．

<b>重要度</b>は，
AIが見つけた個々の校正候補について，
どの程度修正が必要かを0～10で評価した値です．

両者は別のものです．

"""


