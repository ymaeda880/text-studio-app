SAVE_TEXT = """
##### 1. 会話履歴の保存

左パネル（サイドバー）の「履歴（保存/復元）」から，
現在の会話履歴をユーザーのパソコンへダウンロードできます．

保存形式は，次の2種類です．

- JSON形式
- TXT形式

---

##### 2. JSON形式

JSON形式は，
会話履歴を後で復元するための正本です．

JSONファイルには，主に次の情報が保存されます．

- 使用していたAIプロバイダー
- 使用していたAIモデル
- 会話履歴
- 文書コンテキスト

文書コンテキストを設定している場合は，
その内容もJSONファイルに含まれます．

履歴を後でAIチャットへ戻す可能性がある場合は，
JSON形式で保存してください．

---

##### 3. TXT形式

TXT形式は，
会話内容を人が読みやすい形で保存します．

TXTファイルには，
ユーザーの質問・指示とAIの回答が，
会話の順番に従って記録されます．

文書コンテキストが設定されている場合は，
文書の種類，文字数および先頭部分も記録されます．

TXT形式は閲覧用です．

TXTファイルをアップロードして，
会話履歴を復元することはできません．

---

##### 4. 保存される履歴の範囲

AIへの送信時には，
会話履歴が長くなりすぎないように，
古い履歴が自動的に省略される場合があります．

ただし，これはAIへ送信する内容だけの制限です．

履歴ファイルを保存する場合は，
画面上に保持されている全会話履歴が保存されます．

そのため，AIへの送信対象から外れた古い会話も，
JSON形式およびTXT形式の履歴には残ります．

---

##### 5. 保存ファイル名

「保存ファイル名」には，
ダウンロードするファイルの名前を入力できます．

拡張子の入力は不要です．

例えば，保存ファイル名に
`AIプロジェクト会合_20260807`
と入力します．

JSON形式でダウンロードした場合は，
`AIプロジェクト会合_20260807.json`
というファイル名になります．

TXT形式でダウンロードした場合は，
`AIプロジェクト会合_20260807.txt`
というファイル名になります．

保存ファイル名を入力しない場合は，
従来どおり，次の名前が使用されます．

- JSON形式：`chat_history.json`
- TXT形式：`chat_history.txt`

---

##### 6. 拡張子

保存ファイル名には，
`.json`や`.txt`を入力する必要はありません．

選択したダウンロード形式に応じて，
拡張子は自動的に付けられます．

---

##### 7. 会話をリセットする前の保存

「会話をリセット」を押すと，
現在の会話履歴は消去されます．

後で会話を確認したり，
続きを再開したりする可能性がある場合は，
リセットする前に履歴を保存してください．

会話を後で復元する場合は，
JSON形式での保存が必要です．
"""


