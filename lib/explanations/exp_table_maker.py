# public API：詳細説明 expander
# ============================================================
def render_table_maker_help_expander(
    *,
    theme: dict[str, Any] | None = None,
    banner_key: str = "navy_dark",
) -> None:
    render_themed_help_expander(
        expander_key=HELP_EXPANDER_KEY,
        expander_title=HELP_EXPANDER_TITLE,
        tabs=HELP_TABS,
        theme=theme,
        banner_key=banner_key,
        expanded=False,
    )


# ============================================================
# expander 設定
# ============================================================
HELP_EXPANDER_KEY = "table_maker_help_expander"
HELP_EXPANDER_TITLE = "📌 詳細説明（クリックで展開）"


# ============================================================
# 詳細説明：入力方法
# ============================================================
INPUT_TEXT = """

##### 1. 表データの入力

Excelなどで対象となる表を選択してコピーし，
「ここに貼り付け」欄へ貼り付けます．

Excelからコピーしたデータは，通常，タブ区切りの表として読み込まれます．

例えば，Excel上で次のような表をコピーします．

```text
項目    2024年度    2025年度
売上    100         120
費用    80          90
```

この表を「ここに貼り付け」欄へ貼り付けると，
3列3行の表として読み込まれます．

CSV形式のテキストも読み込めます．

---

##### 2. 注の入力

表の下に注記を付ける場合は，
「注」欄へ文章を入力します．

入力した注記は，Word形式およびHTML形式の表の下に表示されます．

注記が不要な場合は，空欄のままで構いません．

---

##### 3. サンプルデータ

サイドバーの「サンプルデータを入れる」をONにすると，
表作成を試すためのサンプルデータが入力欄に表示されます．

表の貼り付け形式やセル結合マーカーの使い方を確認する場合に利用できます．
"""


# ============================================================
# 詳細説明：ヘッダー
# ============================================================
HEADER_TEXT = """

##### 1. ヘッダー行数

表の先頭から何行を列見出しとして扱うかを指定します．

例えば，次の表では，先頭の1行が見出しです．

```text
項目    金額    備考
売上    100     確定値
費用    80      暫定値
```

この場合は，「ヘッダー行数」を1にします．

複数行の見出しがある場合は，その行数を指定します．

例えば，次の表では，先頭の2行が見出しです．

```text
区分    2024年度    <同左>
項目    上期        下期
売上    50          50
```

この場合は，「ヘッダー行数」を2にします．

ヘッダーがない場合は，0を指定してください．

---

##### 2. ヘッダー列数

表の左端から何列を行見出しとして扱うかを指定します．

例えば，次の表で「項目」列を行見出しとして扱う場合は，
「ヘッダー列数」を1にします．

```text
項目    2024年度    2025年度
売上    100         120
費用    80          90
```

左端から2列を行見出しとして扱う場合は，
「ヘッダー列数」を2にします．

---

##### 3. ヘッダーの表示

ヘッダー行およびヘッダー列には，
ヘッダー用の背景色，文字色，フォントサイズなどが適用されます．

「ヘッダーも同じサイズ」をOFFにすると，
ヘッダー文字は本文より1ポイント大きくなります．

ONにすると，ヘッダーと本文は同じフォントサイズになります．
"""


# ============================================================
# 詳細説明：セル結合・改行
# ============================================================
MARKER_TEXT = """

##### 1. 「<同上>」による縦結合

上のセルと縦方向に結合する場合は，
結合対象となるセルに次のマーカーを入力します．

```text
<同上>
```

例えば，次のように入力します．

```text
区分    項目    金額
収入    売上    100
<同上>  雑収入  20
```

この場合，「収入」のセルと，その下の「<同上>」のセルが
縦方向に結合されたように表示されます．

「<同上>」が連続する場合は，
その上にある基準セルまで連続して結合されます．

---

##### 2. 「<同左>」による横結合

左のセルと横方向に結合する場合は，
結合対象となるセルに次のマーカーを入力します．

```text
<同左>
```

例えば，次のように入力します．

```text
年度    上期    <同左>
項目    4月     5月
```

この場合，「上期」のセルと，その右側の「<同左>」のセルが
横方向に結合されたように表示されます．

「<同左>」が連続する場合は，
左側にある基準セルまで連続して結合されます．

---

##### 3. セル内改行

セル内で文章を改行する場合は，
改行したい位置に次のマーカーを入力します．

```text
<改行>
```

例えば，次のように入力します．

```text
第1行<改行>第2行
```

Word形式およびHTML形式では，次のように表示されます．

```text
第1行
第2行
```

Excelのセル内改行が貼り付け時に適切に保持されない場合は，
「<改行>」マーカーを使用してください．

---

##### 4. マーカー処理の有効・無効

サイドバーでは，次の処理を個別に有効または無効にできます．

- 「<同上>」による縦結合
- 「<同左>」による横結合

マーカーを通常の文字として表示したい場合は，
該当する結合処理をOFFにしてください．

---

##### 5. Wordでのセル結合

Word出力では，セルを物理的には結合しません．

結合対象セルの内容を空にし，
結合範囲内の罫線を消すことによって，
セルが結合されているように表示します．

HTMLプレビューでは，rowspanおよびcolspanを使用して，
実際にセルを結合して表示します．
"""


# ============================================================
# 詳細説明：スタイル・列幅
# ============================================================
STYLE_TEXT = """

##### 1. プリセット

表の基本デザインは，プリセットから選択できます．

プリセットを選択すると，次のような設定がまとめて反映されます．

- ヘッダー背景色
- ヘッダー文字色
- ヘッダー太字
- 本文背景色
- 本文文字色
- フォント
- 横罫線
- 縦罫線
- 外枠
- ゼブラ行

必要に応じて，「詳細設定」を開いて個別に変更できます．

---

##### 2. フォントサイズ

サイドバーの「基本フォントサイズ」で，
本文のフォントサイズを指定します．

指定できる範囲は5ptから16ptです．

「ヘッダーも同じサイズ」をOFFにすると，
ヘッダーは本文より1pt大きくなります．

---

##### 3. 詳細設定

「詳細設定」では，次の項目を変更できます．

- ヘッダー背景色
- ヘッダー文字色
- ヘッダー太字
- 本文背景色
- 本文文字色
- フォント
- 内側の横罫線
- 内側の縦罫線
- 外枠
- ゼブラ行

---

##### 4. 列幅モード

列幅は，次の3つの方法から選択できます．

###### 均等

すべての列を同じ幅にします．

表全体の幅を列数で均等に分割します．

###### 自動（文字数で可変）

各列に含まれる文字数を基準として，
列幅を自動的に調整します．

文字数の多い列は広く，
文字数の少ない列は狭く設定されます．

###### 手動（cm指定）

各列の幅をセンチメートル単位で指定します．

Word文書の標準的な本文幅を想定し，
列幅の合計は約16cmが推奨されます．

手動設定では，次の補助機能を利用できます．

- すべての列を均等幅にする
- 文字数を基準に自動設定する
- 列幅の合計を16cmに調整する
"""


# ============================================================
# 詳細説明：出力・注意
# ============================================================
OUTPUT_TEXT = """

##### 1. 表の作成

設定が完了したら，
「表作成（Word .docxを生成＆画面表示）」ボタンを押します．

表データが正常に読み込まれると，
次の情報が表示されます．

- 本文の行数
- 表の列数
- ヘッダー行数
- ヘッダー列数
- 列幅モード

---

##### 2. データ確認

読み込んだ表は，
Streamlitのデータフレームとして表示されます．

この表示では，貼り付けた表の列数や内容を確認できます．

セル結合の状態は，その下に表示されるHTMLプレビューで確認してください．

---

##### 3. HTMLプレビュー

HTMLプレビューでは，
次の設定が反映されます．

- ヘッダー行
- ヘッダー列
- セル結合
- セル内改行
- 背景色
- 文字色
- フォントサイズ
- 列幅
- 罫線
- ゼブラ行
- 注記

---

##### 4. Word形式の出力

作成した表は，Word形式でダウンロードできます．

出力ファイル名は，次のとおりです．

```text
table_generated.docx
```

Word形式には，表のスタイル，列幅，セル結合表示および注記が反映されます．

---

##### 5. HTML形式の出力

作成した表は，HTML形式でもダウンロードできます．

出力ファイル名は，次のとおりです．

```text
table_generated.html
```

HTMLファイルは，ブラウザーで開いて確認できます．

---

##### 6. 注意事項

- 貼り付けた表の各行で列数が一致していない場合は，正しく処理できないことがあります．
- セル結合マーカーは，半角記号を使用した「<同上>」「<同左>」を入力してください．
- 結合元となるセルが存在しない位置にマーカーを入力すると，意図した結果にならないことがあります．
- 手動列幅の合計が大きすぎる場合は，Word文書の表示幅を超えることがあります．
- WordとHTMLでは，表示方法の違いにより，見た目が完全に一致しない場合があります．
"""


