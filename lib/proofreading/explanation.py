# ============================================================
# 詳細説明：ロジック/注意
# ============================================================
LOGIC_TEXT = """

##### 1. このアプリの目的

- 文章そのものを書き換えるのではなく，**「どのページのどの行を，どのような理由で直すとよいか」** という校正方針（チェックリスト）を作ることを目的としています．
- 出力されるのは，頁・行・重要度・原文・修正案・理由などをまとめた **Markdown形式の表** です．
- 最終的な原稿の修正は，利用者ご自身が Word 等で行ってください．

---

##### 2. テキストの扱いと行番号の付け方

- 入力は，**貼り付けテキスト** または **.docx / .txt / テキスト層付き .pdf** に対応しています．
- 画像だけのPDF（テキスト層なし）は対象外です．その場合は，事前にOCRでテキスト化してください．
- 読み込んだテキストは改行ごとに分割し，ページ行数に基づいて行番号を付けてプレビュー表示します．
- この行番号は，校正方針の表に出てくる「頁」「行」と対応します．

---

##### 3. 校正方針テーブルの生成ロジック

- 解析モードを選択すると，そのモードに応じたプロンプトを組み立てて AI に渡します．
- 必要に応じて追加プロンプトを指定することで，外来語の扱い・固有名詞の扱い・文体などの方針を補足できます．
- AI は，頁，行，重要度，原文，修正案，理由などを含む表を生成します．

---

##### 4. レポート（PDF / Word）の出力

- 解析が終わると，原文（行番号つきプレビュー）と校正方針を含むレポートを作成できます．
- 出力形式は PDF（.pdf）または Word（.docx）です．
- PDF版では，原文と校正方針を表として整形して出力します．
- Word版では，原文および校正方針をテキストとして貼り込んだレポートを生成します．

---

##### 5. AI校正に関する重要な注意事項

このアプリの校正方針は，OpenAI の生成AIによって自動生成された **「AIの提案」** であり，
「正解」や「公式見解」ではありません．

以下の点に注意してください．

- 提案はあくまで AI の意見であり，常に正しいとは限りません．
- 文法・用語・専門内容などについて誤った判断をする可能性があります．
- 文脈を誤解したり，見当違いの修正案・理由を出す場合があります．
- 同じ原稿を同じ設定で解析しても，結果が毎回同じになるとは限りません．
- 最終的な採否の判断と責任は，利用者にあります．

---

##### 6. 個人情報・機密情報とセキュリティ

- このアプリでは，校正方針の解析に OpenAI の GPT API などの生成AIを使用しています．
- 入力されたテキストはサーバーから OpenAI などの API エンドポイントに送信されます．
- 本アプリ側で匿名化処理が行われるわけではありません．
- 機密性の高い情報が含まれる場合は，可能な範囲でマスキング・置き換えを行ってから利用してください．

---

##### 7. 想定している使い方

このアプリは，「どこを優先的に見直すべきか」「どういう観点で直すとよいか」を
一覧化するための補助ツールとして設計されています．

AI が示した内容をヒントとして活用しつつ，
最終的な文章表現は利用者ご自身の判断で整えてください．

</div>
"""


