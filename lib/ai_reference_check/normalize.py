# AI参照チェック：テキスト正規化
#
# 機能：
# - AIへ渡す前に改行・空白を整理する
# - 図/表 と番号が改行で分断されたケースを補正する
# ============================================================

from __future__ import annotations

# ============================================================
# imports
# ============================================================
import re


# ============================================================
# 図表キー改行またぎ補正
# ============================================================
def normalize_figure_key_breaks(text: str) -> str:
    s = str(text or "")

    s = re.sub(
        r"(図表|図|表)\s*\n\s*(\d+(?:\.\d+)*(?:-\d+)?(?:\(\d+/\d+\))?)",
        r"\1\2",
        s,
    )

    return s


# ============================================================
# AI入力用テキスト正規化
# ============================================================
def normalize_ai_text(text: str) -> str:
    s = str(text or "")

    s = normalize_figure_key_breaks(s)
    s = s.replace("\r\n", "\n").replace("\r", "\n")
    s = re.sub(r"[ \t]+", " ", s)
    s = re.sub(r"\n{3,}", "\n\n", s)

    return s.strip()


# ============================================================
# 1行表示用正規化
# ============================================================
def normalize_one_line(text: str) -> str:
    s = normalize_ai_text(text)
    s = re.sub(r"\s+", " ", s)

    return s.strip()