from __future__ import annotations

# ============================================================
# imports（stdlib / typing）
# ============================================================
import json
from typing import Any, Dict


# ============================================================
# system prompt
# ============================================================
FIGURE_TABLE_CHECK_SYSTEM_PROMPT = """
あなたは日本語報告書の図表参照チェック担当です。

あなたの役割は、すでにプログラムで抽出された
「図表タイトル一覧」と「本文中の図表参照一覧」をもとに、
本文中の参照が、文脈上、正しい図表タイトルを参照しているかを確認することです。

重要：
- 図表番号の抽出はすでにプログラム側で実施済みです。
- あなたは抽出をやり直さないでください。
- 存在しない情報を推測で補わないでください。
- 判断できない場合は need_review としてください。
- 出力は JSON のみとし、説明文やMarkdownは出力しないでください。
""".strip()


# ============================================================
# user prompt 生成
# ============================================================
def build_figure_table_check_prompt(payload: Dict[str, Any]) -> str:
    payload_json = json.dumps(
        payload,
        ensure_ascii=False,
        indent=2,
    )

    return f"""
以下のJSONデータをもとに、図・表・図表の参照ずれをチェックしてください。

# 入力データの意味

- titles:
  図表タイトル一覧です。
  kind は「図」「表」「図表」のいずれかです。
  label は図表キーです。
  title は図表タイトルです。

- references:
  本文中で参照されている図表一覧です。
  context または line_text を見て、本文が何を説明しているか判断してください。

- machine_checks:
  プログラム側で機械的に判定した結果です。
  未引用、見出しなし参照、重複、欠番などが含まれます。

# チェックしてほしい内容

1. 本文中の参照が、対応する図表タイトルの内容と文脈的に合っているか
2. 図と表を取り違えている可能性がないか
3. 図表番号が前後の文脈から見てずれている可能性がないか
4. machine_checks に含まれる問題を、必要に応じて issues に反映すること
5. 判断できないものは need_review とすること

# 注意点

- 表3.1.5-1(1/3)、表3.1.5-1(2/3) のような分割表は、同一表の分割として扱ってください。
- (1/3)、(2/3) の違いだけで重複エラーにしないでください。
- 図表番号の抽出はプログラム側の結果を信頼してください。
- 正しい番号を推定で断定しないでください。
- ただし、文脈上「別の図表を参照している可能性が高い」場合は warning としてください。

# 出力形式

以下のJSONのみを返してください。

{{
  "summary": {{
    "total_titles": 0,
    "total_references": 0,
    "error_count": 0,
    "warning_count": 0,
    "need_review_count": 0
  }},
  "issues": [
    {{
      "severity": "warning",
      "type": "context_mismatch",
      "label": "図3.1.1-2",
      "message": "本文の内容と図表タイトルの内容が一致しない可能性があります。",
      "context": "本文中の参照箇所",
      "matched_title": "対応する図表タイトル",
      "reason": "判断理由"
    }}
  ],
  "checks": [
    {{
      "label": "表3.1.1-1",
      "status": "ok",
      "context": "本文中の参照箇所",
      "matched_title": "対応する図表タイトル",
      "reason": "本文は地域気象観測所の所在地を説明しており、表タイトルと整合しています。"
    }}
  ]
}}

# 入力JSON

{payload_json}
""".strip()