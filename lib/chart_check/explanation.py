# ============================================================
LOGIC_TEXT = """
<div style="line-height:1.7">

## 1. 図・表・図表の見出しの拾い方

「図」「表」「図表」に続く番号を正規表現で検出します．

例：

- 図 3.2-1
- 表4-3
- 図表 2-1
- 表3.1.5-1(1/3)

検出した文字列について，行の中での位置や周辺の文字を見て，

- 見出し（キャプション）
- 本文からの参照

に分けます．

---

## 2. 見出しとみなす主な条件

次のような場合は，図表の見出しとして扱います．

- 「図／表／図表＋番号」が行頭にある
- 番号の直後が助詞で始まっていない
- 同じ行に句点「。」がない
- タイトルらしい短い行になっている

例：

`図 3.1-2 鉄道駅周辺の立地状況`

これは見出しとして判定します．

---

## 3. 本文参照とみなす主な条件

次のような場合は，本文中の参照として扱います．

- 行の途中に出てくる
- 「図3-1を参照」のように助詞が続く
- 同じ行に句点「。」があり，文章の一部になっている

例：

`調査地点の位置は図3.1-2に示す。`

これは本文参照として判定します．

---

## 4. 図表キーとベースキー

見出しと本文参照を突き合わせるために，図表番号の表記を正規化します．

正規化では，主に次の処理を行います．

- 全角数字を半角数字へ変換
- 全角括弧を半角括弧へ変換
- ドット類を統一
- ハイフン類を統一
- 余分な空白を削除

例：

`図 ３．１ー２ （１／３）`

は，

`図3.1-2(1/3)`

のように扱います．

この正規化後の文字列を，図表キーとして使います．

---

## 5. ベースキーによる緩い照合

図表には，分割ページを示す `(1/3)` や `(2/3)` が付くことがあります．

例：

- 表3.1.5-1(1/3)
- 表3.1.5-1(2/3)
- 表3.1.5-1(3/3)

本文では，これらをまとめて

`表3.1.5-1`

と参照することがあります．

このため，末尾の分割表記を取り除いたベースキーでも照合します．

例：

- 表3.1.5-1(1/3) → 表3.1.5-1
- 表3.1.5-1(2/3) → 表3.1.5-1
- 図4.2-3（続き） → 図4.2-3

これにより，完全一致だけでなく，同じ図表シリーズとしての照合ができます．

---

## 6. 続きページの判定

同じ図表キーが複数ページに出ている場合でも，次の条件を満たすときは真の重複ではなく，
続きページとみなします．

- PDFページが連続している
- 見出しタイトルの本体部分が同じである
- `(1/3)`, `(2/3)` などの分割番号が自然に並んでいる

この条件を満たさない場合は，真の重複の可能性として表示します．

---

## 7. 欠番・開始番号のチェック

図・表・図表ごとに，番号系列を取り出します．

例：

- 図4.2-1
- 図4.2-2
- 図4.2-3

このような系列について，

- 1番から始まっているか
- 途中に欠番がないか

を確認します．

</div>
"""

