# 詳細説明：ロジック・注意事項
# ============================================================
LOGIC_TEXT = """
##### 1. このアプリの目的

このアプリは，文書をAIで翻訳するための補助ツールです．

日本語，英語，フランス語，ドイツ語，スペイン語への翻訳に対応しています．

また，「その他の言語」を選択することで，任意の翻訳先言語を指定できます．

---

##### 2. 翻訳先言語の指定

翻訳先言語は，「翻訳方向」から選択します．

初期値は「日本語に翻訳」です．

固定選択肢は次の通りです．

- 日本語に翻訳
- 英語に翻訳
- フランス語に翻訳
- ドイツ語に翻訳
- スペイン語に翻訳
- その他の言語

「その他の言語」を選択した場合は，表示された入力欄に翻訳先の言語を入力してください．

翻訳先の言語が入力されていない場合は，翻訳を実行できません．

---

##### 3. 入力方法

入力は次に対応しています．

- 貼り付けテキスト
- ファイルアップロード
- Inboxからの読み込み

対応するファイル形式は次の通りです．

- .txt
- .docx
- テキスト層付き .pdf

画像だけで構成されたPDFは対象外です．

画像PDFを翻訳する場合は，先にOCRを実行して，文字をテキスト化してください．

---

##### 4. 行番号

翻訳前の文章には，原文と翻訳結果の対応を確認しやすくするため，行番号を付けてAIへ送信します．

行番号は，次のような形式です．

- ［0001］文章の1行目です．
- ［0002］文章の2行目です．

AIには，この行番号を維持したまま翻訳するよう指示します．

翻訳結果では，次の2種類を表示します．

- 行番号付きの翻訳結果
- 行番号を除去した翻訳結果

行番号付きの翻訳結果は，原文と訳文の対応を確認するために使用できます．

---

##### 5. 要約

翻訳結果とは別に，日本語の要約を作成できます．

要約設定では，次のいずれかを選択します．

- 要約なし
- 要約あり

「要約あり」を選択した場合は，次の長さから選択できます．

- 300字程度
- 600字程度
- 1000字程度

要約は翻訳結果を基に作成され，日本語で出力されます．

翻訳先が英語，フランス語，ドイツ語，スペイン語，その他の言語であっても，要約は日本語です．

---

##### 6. 翻訳結果の保存

翻訳結果は，次の形式で保存できます．

- Text
- Word
- PDF

生成したファイルには，主に次の内容が含まれます．

- 原文
- 使用モデル
- 翻訳先言語
- 追加プロンプト
- 行番号付き翻訳結果
- 行番号なし翻訳結果
- 要約結果
- 使用トークン情報

生成したファイルは，端末へダウンロードするほか，Inboxへ保存できます．

---

##### 7. AI翻訳に関する注意

AI翻訳は，常に正確であるとは限りません．

特に次の文章では，翻訳結果を慎重に確認してください．

- 専門用語を含む文章
- 法令や条例
- 契約書
- 技術文書
- 固有名詞を多く含む文章
- 数値や単位が重要な文章
- 曖昧な表現を含む文章
- 複数の言語が混在する文章

重要な文書では，必ず利用者が原文と翻訳結果を照合してください．

---

##### 8. 「その他の言語」に関する注意

「その他の言語」では，入力された言語名をAIへの翻訳指示に使用します．

一般的な言語名を，具体的に入力してください．

良い入力例は次の通りです．

- イタリア語
- 簡体字中国語
- 繁体字中国語
- ブラジルポルトガル語
- 韓国語

「外国語」「ヨーロッパの言語」など，翻訳先が特定できない入力は避けてください．

方言，古語，地域別の表記を指定する場合は，追加プロンプトにも条件を入力してください．

---

##### 9. 機密情報について

このページでは，入力した文章をAI APIへ送信します．

個人情報や機密情報は，入力前に削除または匿名化してください．

特に次の情報を含む文書は，そのまま入力しないでください．

- 氏名
- 住所
- 電話番号
- メールアドレス
- 顧客情報
- 契約上の秘密情報
- 未公開の業務情報
- パスワードや認証情報
"""


