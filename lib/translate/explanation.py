POLICY_TEXT = """
##### 翻訳方針

このページでは，文章を要約せず，できるだけ原文の構造を保って翻訳します．

主な方針は次の通りです．

- 各文をまとめない
- 意味を補って意訳しすぎない
- 原文にない内容を追加しない
- 文を省略しない
- 原文の順序を保つ
- 数値，日付，見出し，固有名詞をできるだけ維持する
- 専門用語や固有名詞をできるだけ一貫して扱う
- 文番号を維持して，原文と訳文の対応を確認しやすくする
- 翻訳結果の前後に説明やコメントを付けない

---

##### 対応する翻訳先言語

翻訳先として，次の言語を選択できます．

- 日本語
- 英語
- フランス語
- ドイツ語
- スペイン語

一覧にない言語へ翻訳する場合は，「その他の言語」を選択してください．

「その他の言語」を選択すると，翻訳先の言語を入力する欄が表示されます．

入力例は次の通りです．

- イタリア語
- 中国語
- 韓国語
- ポルトガル語
- ベトナム語

言語名だけを入力しても，「○○語に翻訳」と入力しても翻訳できます．

---

##### 原文の言語

このページでは，翻訳元の言語を選択する必要はありません．

AIが入力された文章の言語を判断し，指定された翻訳先言語へ翻訳します．

ただし，複数の言語が混在する文章や，短い単語だけの文章では，原文の言語を正しく判断できない場合があります．

その場合は，追加プロンプトに次のような指示を入力してください．

- 原文はフランス語です．
- 英語部分だけを日本語へ翻訳してください．
- 固有名詞は英語表記のまま残してください．

---

##### 追加プロンプト

追加プロンプトには，翻訳時に特に守ってほしい条件を入力できます．

入力例は次の通りです．

- 専門用語は原文に近い表現で訳してください．
- 固有名詞は原文表記を残してください．
- 法令名は正式名称を使用してください．
- 敬体で翻訳してください．
- 箇条書きの形式を維持してください．
- 表の項目順を変更しないでください．

追加プロンプトは任意です．
"""


