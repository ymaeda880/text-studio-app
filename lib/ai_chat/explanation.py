# ============================================================
# バナー色に合わせた詳細説明Expanderを表示する
# 共通テンプレートにテーマとバナーキーを渡し，初期状態は閉じる
# ============================================================
def render_ai_chat_help_expander(
    *,
    theme: dict[str, Any] | None = None,
    banner_key: str = 'purple_light',
) -> None:
    render_themed_help_expander(
        expander_key=HELP_EXPANDER_KEY,
        expander_title=HELP_EXPANDER_TITLE,
        tabs=HELP_TABS,
        theme=theme,
        banner_key=banner_key,
        expanded=False,
    )


# ============================================================
# 詳細説明Expanderの設定
# ============================================================
HELP_EXPANDER_KEY = 'ai_chat_help_expander'
HELP_EXPANDER_TITLE = '📌 詳細説明（クリックで展開）'


# ============================================================
# 詳細説明：ジョブの作成と会話の進め方
# ============================================================
USAGE_TEXT = """
##### ① ジョブの設定

「新規会話から作成」または「保存済みジョブを選択」を選びます．
保存済みジョブは，AI回答から付けられたタイトルと作成日時で選択できます．
新しいテーマの会話を始めるときは，「新しい会話を始める」を押します．

##### ② AIとの会話

サイドバーでモデルを選び，質問・指示を入力して「送信」を押します．
追加質問では，保存している会話全体を今回の質問と一緒にAIへ送信します．
会話が長くなるほど，入力トークン数と費用が増えます．

「最大出力トークン」は回答の出力上限です．回答の長さを保証する設定ではありません．
指定できる上限はモデルによって異なります．

##### AI利用状況

直近のAI実行について，費用・入力／出力トークン数・AI使用時間を表示します．
回答を利用する際は，内容や根拠となる情報を確認してください．
"""


# ============================================================
# 詳細説明：前提文書と会話履歴
# ============================================================
CONTEXT_TEXT = """
##### 前提文書（任意）

Word・PDF・テキスト・Markdown・JSONをアップロードするか，文章を貼り付けます．
「前提文書を保存」を押すと，そのジョブの会話の参考資料として設定されます．
前提文書は先頭15,000文字までです．解除する場合は「前提文書を解除」を押します．

##### 会話の引き継ぎ

同じジョブで質問を続けると，過去の質問・回答と前提文書をAIへ渡します．
別のテーマは新しい会話に分けると，目的の会話を探しやすくなります．
モデルの入力上限を超えた場合は，エラー表示を確認してください．
"""


# ============================================================
# 詳細説明：通常検索と詳細検索
# ============================================================
SEARCH_TEXT = """
##### ネット検索をする

「AIとの会話」の上部でONにすると，Web検索を利用して回答します．
OFFの場合は，今回の回答生成でWeb検索ツールを使用しません．
Web検索はOpenAIとGeminiで利用できます．Azureでは検索チェックを使用できません．

##### 通常検索と詳細検索

- 通常検索：主な参考URL一覧を最大10件表示します．
- 詳細検索：複数の情報源を調べ，取得した参考URLの件数は制限しません．

これは参考URL一覧の表示上限です．必ず10件のURLが取得される意味ではありません．
APIから取得できた出典を表示し，URLが取得できなかった場合はその旨を表示します．
検索を利用すると，処理時間や費用が増える場合があります．
"""


# ============================================================
# 詳細説明：保持件数・ダウンロード・費用
# ============================================================
SAVE_TEXT = """
##### 最新5ジョブの保存

ジョブは利用者ごとに，作成順で最新5件を保持します．
6件目を保存すると，最も古いジョブを自動削除します．
残しておきたい会話は，あらかじめJSON等でダウンロードしてください．

##### ③ 保存・ダウンロード

「現在の会話を保存」で保存できます．AI回答の生成に成功した際にも自動保存します．
JSONには，会話全体と前提文書などを含めます．
サイドバーの「JSONの取り込み」から，新規ジョブとして復元できます．
以前のAIチャットページで保存した会話JSONも取り込めます．

Word・PDFでは，会話全体・前提文書・取得した出典を出力します．
「Word・PDFを作成」を押すと，ダウンロードボタンが表示されます．

##### 費用の確認

AI利用状況では，取得できた利用量に基づいて料金を表示します．
Web検索を使用した場合は，検索料金の内訳も確認できます．
料金は概算であり，無料枠や契約割引は反映しない場合があります．
"""


# ============================================================
# 詳細説明のタブ構成
# ============================================================
HELP_TABS = [
    ('使い方', USAGE_TEXT),
    ('前提文書・会話履歴', CONTEXT_TEXT),
    ('ネット検索', SEARCH_TEXT),
    ('保存・費用', SAVE_TEXT),
]
