# -*- coding: utf-8 -*-
# text_studio_app/lib/slide_creation/table/models.py
# ============================================================
# SlideTex 表データモデル
#
# 機能：
# - 表全体の設定を保持する
# - 表のセル値を保持する
# - ヘッダー行数・列数を保持する
# - セル結合指定を保持する
#
# 方針：
# - PowerPoint描画処理には依存しない
# - SlideTex解析結果を単純なデータ構造として保持する
# - 表の構文解析と描画処理の間で共通利用する
# ============================================================

from __future__ import annotations

# ============================================================
# imports
# ============================================================
from dataclasses import dataclass, field


# ============================================================
# セル結合指定
# ============================================================
TABLE_MERGE_UP = "<同上>"
TABLE_MERGE_LEFT = "<同左>"


# ============================================================
# 表セル
# ============================================================
@dataclass(frozen=True)
class TableCell:
    # --------------------------------------------------------
    # セル本文
    # --------------------------------------------------------
    text: str = ""

    # --------------------------------------------------------
    # 結合指定
    #
    # ""
    #     通常セル
    #
    # "up"
    #     上のセルと結合する
    #
    # "left"
    #     左のセルと結合する
    # --------------------------------------------------------
    merge_direction: str = ""


# ============================================================
# 表ヘッダー
# ============================================================
@dataclass(frozen=True)
class TableHeaderSpec:
    # --------------------------------------------------------
    # 先頭からヘッダーとして扱う行数
    # --------------------------------------------------------
    row_count: int = 0

    # --------------------------------------------------------
    # 左端からヘッダーとして扱う列数
    # --------------------------------------------------------
    column_count: int = 0


# ============================================================
# 表定義
# ============================================================
@dataclass(frozen=True)
class TableDefinition:
    # --------------------------------------------------------
    # 表スタイル
    # --------------------------------------------------------
    style_key: str = "simple"

    # --------------------------------------------------------
    # 表本体のフォントサイズ
    #
    # None：
    #     表スタイルの既定値を使用する．
    #
    # 数値：
    #     \begin{table,...}のfont_size指定を使用する．
    # --------------------------------------------------------
    font_size: int | None = None

    # --------------------------------------------------------
    # 表題
    # --------------------------------------------------------
    caption: str = ""

    # --------------------------------------------------------
    # ヘッダー設定
    # --------------------------------------------------------
    header: TableHeaderSpec = field(
        default_factory=TableHeaderSpec,
    )

    # --------------------------------------------------------
    # 表データ
    # --------------------------------------------------------
    rows: tuple[tuple[TableCell, ...], ...] = field(
        default_factory=tuple,
    )

    # --------------------------------------------------------
    # 行数
    # --------------------------------------------------------
    @property
    def row_count(self) -> int:
        return len(
            self.rows,
        )

    # --------------------------------------------------------
    # 列数
    # --------------------------------------------------------
    @property
    def column_count(self) -> int:
        if not self.rows:
            return 0

        return max(
            len(row)
            for row in self.rows
        )

    # --------------------------------------------------------
    # 表が空か
    # --------------------------------------------------------
    @property
    def is_empty(self) -> bool:
        return (
            self.row_count <= 0
            or self.column_count <= 0
        )